/** 언어 코드에 맞는 문구 묶음. 모르는 언어는 한국어. */
export const dict = (lang: string): Dict => ALL[lang] ?? ko;

/** "{n}일 전" 같은 문구의 {n} 자리에 값을 넣습니다. */
export const fill = (t: string, v: Record<string, string | number>) => t.replace(/\{(\w+)\}/g, (_, k: string) => String(v[k] ?? ''));
